function pick(arr: string[]): string {
  return arr[Math.floor(Math.random() * arr.length)];
}

export function applyVariants(template: string, vars?: Record<string, string[]>): string {
  if (!vars) return template;
  let result = template;
  for (const [key, options] of Object.entries(vars)) {
    result = result.replaceAll(`[${key}]`, pick(options));
  }
  return result;
}

