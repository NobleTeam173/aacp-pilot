// Builds src/knowledge/career-kb.js — ACIA™'s verified knowledge base — from the data
// already published and cited in public/career-navigator.html, so the page stays the
// single source of truth. Run: node scripts/build-career-kb.mjs  (also run by `npm run build`).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import vm from 'node:vm';

const html = readFileSync(new URL('../public/career-navigator.html', import.meta.url), 'utf8');

// Return the source from `startMarker` to the end of the statement whose brackets close first.
function sliceDecl(startMarker) {
  const start = html.indexOf(startMarker);
  if (start < 0) throw new Error(`KB build: "${startMarker}" not found in career-navigator.html`);
  let i = html.indexOf('=', start) + 1, depth = 0, seen = false, q = null;
  for (; i < html.length; i++) {
    const c = html[i], n = html[i + 1];
    if (q) { if (c === '\\') { i++; continue; } if (c === q) q = null; continue; }
    if (c === '/' && n === '/') { i = html.indexOf('\n', i); continue; }
    if (c === '/' && n === '*') { i = html.indexOf('*/', i) + 1; continue; }
    if (c === '"' || c === "'" || c === '`') { q = c; continue; }
    if (c === '[' || c === '{' || c === '(') { depth++; seen = true; }
    else if (c === ']' || c === '}' || c === ')') { depth--; }
    if (seen && depth === 0) { const end = html.indexOf(';', i); return html.slice(start, end + 1); }
  }
  throw new Error(`KB build: unterminated declaration ${startMarker}`);
}
// Everything from one marker up to (not including) another — for blocks with helper functions.
function sliceRange(fromMarker, toDeclMarker) {
  const a = html.indexOf(fromMarker), b = html.indexOf(toDeclMarker);
  if (a < 0 || b < 0 || b < a) throw new Error(`KB build: range ${fromMarker} → ${toDeclMarker} not found`);
  return html.slice(a, b) + sliceDecl(toDeclMarker);
}

const src = [
  sliceDecl('const PATHWAYS = ['),
  sliceDecl('const COMPARE_CAREERS = ['),
  sliceRange('var MC_CHECKED =', 'var MC_PROGRAMS = ['),
  'this.__kb = { PATHWAYS, COMPARE_CAREERS, MC_CHECKED, MC_FACTS_CHECKED, MC_COURSES, MC_SUBJECT_NAMES, MC_SECTORS, MC_EXTRA_CAREERS, MC_CAREER_FACTS, MC_ALIS, MC_TYPES, MC_PROGRAMS };',
].join('\n');
const ctx = {};
vm.createContext(ctx);
vm.runInContext(src.replace(/^const /gm, 'var '), ctx, { timeout: 2000 });
const k = ctx.__kb;

const plain = v => JSON.parse(JSON.stringify(v));
const kb = {
  builtFrom: 'public/career-navigator.html',
  verified: { requirements: k.MC_CHECKED, facts: k.MC_FACTS_CHECKED },
  sectors: plain(k.MC_SECTORS),
  subjects: plain(k.MC_SUBJECT_NAMES),
  routeTypes: plain(k.MC_TYPES),
  aviation: plain(k.PATHWAYS),            // 15 aviation & aerospace pathways (Transport Canada etc.)
  compare: plain(k.COMPARE_CAREERS),      // cost, demand, time to entry, licences (cited)
  extraCareers: plain(k.MC_EXTRA_CAREERS),// engineering, healthcare, trades
  careerFacts: plain(k.MC_CAREER_FACTS),  // ALIS wages + outlook (non-aviation)
  alisBase: k.MC_ALIS,
  courses: plain(k.MC_COURSES),           // Alberta high school courses
  programs: plain(k.MC_PROGRAMS),         // cited admission requirements
};
mkdirSync(new URL('../src/knowledge/', import.meta.url), { recursive: true });
writeFileSync(new URL('../src/knowledge/career-kb.js', import.meta.url),
  '// GENERATED by scripts/build-career-kb.mjs from public/career-navigator.html — do not edit by hand.\n' +
  'export default ' + JSON.stringify(kb) + ';\n');
console.log(`career KB: ${kb.aviation.length} aviation pathways, ${kb.compare.length} compare entries, ${kb.extraCareers.length} other careers, ${kb.programs.length} programs, ${kb.courses.reduce((n, g) => n + g.items.length, 0)} courses (requirements checked ${kb.verified.requirements})`);
